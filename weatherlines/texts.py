def plural(n: int, forms: list[str]) -> str:
    """Форма слова после числа: 1 разряд, 2 разряда, 5 разрядов (правило общее для русского и украинского)."""
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return forms[1]
    return forms[2]


def tr(lang: str) -> dict:
    return T["uk" if lang == "uk" else "ru"]


def local_now(tz: str, ts: float | None = None) -> datetime:
    zone = ZoneInfo(tz)
    return datetime.fromtimestamp(ts, zone) if ts else datetime.now(zone)


def fmt_time(tz: str, ts: float | None = None) -> str:
    return local_now(tz, ts).strftime("%H:%M")


def fmt_date(lang: str, day: datetime) -> str:
    return f"{day.day} {tr(lang)['months'][day.month - 1]}"


def fmt_temp(t: float) -> str:
    t = round(t)
    return f"+{t}°" if t > 0 else f"{t}°".replace("-", "−")


def fmt_temp_range(values: list[float]) -> str:
    lo, hi = round(min(values)), round(max(values))
    return fmt_temp(lo) if lo == hi else f"{fmt_temp(lo)[:-1]}…{fmt_temp(hi)}"
